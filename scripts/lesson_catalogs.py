def load_catalog(name,doc):
    source=CATALOGS[name]
    if source.endswith('.json'):
        from card_lessons import make_lessons
        specs=json.loads((Path(__file__).resolve().parents[1]/source).read_text())
        return make_lessons(specs,doc)
    factory=importlib.import_module(source).lessons
    return factory() if name=='foundation' else factory(doc)

def load_catalogs(names,doc):
    result=[];seen=set()
    for name in dict.fromkeys(names):
        for lesson in load_catalog(name,doc):
            vid=lesson['video_id']
            if vid in seen:raise ValueError('Duplicate video in selected catalogs: '+vid)
            seen.add(vid);result.append(lesson)
    return result
